def test_the_v1_design_matrix_is_bit_for_bit_what_it_was() -> None:
    """Same names, same order, same numbers as the shipped module.

    ``spec=None`` — which is what every caller written before the design
    spec passes — has to keep meaning exactly the columns that shipped.
    ``assert_array_equal`` rather than ``approx`` because a NaN in the
    design is a value here: "this run never wrote that column" has to
    land in the same place it always did.
    """
    leads = tuple(GOLDEN["design_leads_one_row"])
    assert leads == GOLDEN_DESIGN_LEADS
    assert list(pp.design_columns(leads)) == GOLDEN["columns"]
    design = pp.build_design(_one_row(), leads)
    assert design.shape == (1, len(GOLDEN["columns"]))
    np.testing.assert_array_equal(design[0], np.array(GOLDEN["one_row"]))


def test_an_empty_spec_is_the_v1_design() -> None:
    """``--design v1`` is a control arm, not a re-implementation of one."""
    leads = GOLDEN_DESIGN_LEADS
    spec = pp.design_spec(None, leads, version=pp.DESIGN_V1)
    assert spec == pp.DesignSpec()
    assert list(pp.design_columns(leads, spec)) == GOLDEN["columns"]
    with_spec = pp.build_design(_one_row(), leads, spec)
    without = pp.build_design(_one_row(), leads)
    np.testing.assert_array_equal(with_spec, without)


def test_the_v1_fit_reproduces_the_shipped_coefficients() -> None:
    """Every coefficient, the standardiser and the predictions, to 1e-9."""
    golden = _golden_features()
    model = pp.fit_postprocess(
        golden["features"], golden["truth"], list(LEADS),
        l2=1.0, design_leads=list(LEADS),
    )
    assert model.kind == pp.KIND_LOGISTIC
    assert model.spec == pp.DesignSpec()
    assert list(model.standardiser.mean) == pytest.approx(
        GOLDEN["scaling_mean"], abs=1e-9,
    )
    assert list(model.standardiser.scale) == pytest.approx(
        GOLDEN["scaling_scale"], abs=1e-9,
    )
    for lead, expected in GOLDEN["fit"].items():
        fitted = model.models[int(lead)]
        assert fitted.intercept == pytest.approx(expected["intercept"], abs=1e-9)
        assert list(fitted.coefficients) == pytest.approx(
            expected["coefficients"], abs=1e-9,
        )
        assert list(fitted.isotonic.raw_breakpoints)[:5] == pytest.approx(
            expected["isotonic_breakpoints"], abs=1e-9,
        )
        assert fitted.n == expected["n"]
        assert fitted.station_offsets == {}
        assert fitted.isotonic_by_season == {}
    predicted = model.predict(golden["features"], 20)[:8]
    assert list(predicted) == pytest.approx(GOLDEN["predict_20_head"], abs=1e-9)


