class _Grid:
    """A stand-in for ``decision_rows.GaugeGrid``, with its exact contract.

    ``outcome`` grades the slots whose END falls in ``(t, t + lead]`` and
    reports unusable where the window runs off the grid or a slot in it
    said nothing. Written out longhand here so ``dry_before`` is tested
    against the definition rather than against another copy of itself.
    """

    def __init__(self, wet: np.ndarray, known: np.ndarray, *, first_sec: int,
                 step_sec: int) -> None:
        self.wet, self.known = np.asarray(wet), np.asarray(known)
        self.first_sec, self.step_sec = int(first_sec), int(step_sec)
        self.n_slots = self.wet.shape[1]

    def outcome(self, t, station, lead_min):
        t = np.asarray(t, dtype=np.int64)
        station = np.asarray(station, dtype=np.int64)
        lo = (t - self.first_sec) // self.step_sec + 1
        hi = (t + int(lead_min) * 60 - self.first_sec) // self.step_sec
        out_wet = np.zeros(t.size, dtype=np.float64)
        usable = np.zeros(t.size, dtype=bool)
        for i in range(t.size):
            if lo[i] < 0 or hi[i] >= self.n_slots or hi[i] < lo[i]:
                continue
            window = slice(int(lo[i]), int(hi[i]) + 1)
            wet = bool(self.wet[station[i], window].any())
            all_known = bool(self.known[station[i], window].all())
            out_wet[i] = 1.0 if wet else 0.0
            usable[i] = wet or all_known
        return out_wet, usable


def _grid(rows: list[str]) -> _Grid:
    """``"..W..."`` per station: ``.`` dry+known, ``W`` wet, ``?`` unknown."""
    wet = np.array([[c == "W" for c in row] for row in rows])
    known = np.array([[c != "?" for c in row] for row in rows])
    return _Grid(wet, known, first_sec=600, step_sec=600)


def test_dry_before_looks_back_a_lagged_hour() -> None:
    """Six 10-minute slots, ending at the decision instant minus the lag."""
    # Slot k ends at 600 * (k + 1). The decision instant is at slot 11's
