@pytest.fixture(scope="module")
def synthetic() -> dict:
    """The golden rows, plus the fold keys and the curve baseline.

    The baseline is generous on purpose: the isotonic curve is fitted IN
    SAMPLE on the very rows it is then scored on, so any win against it
    is a win against the best a fraction-only calibration could manage.
    """
    from dmi_nowcast_core.calibrate import fit_isotonic

    golden = _golden_features()
    fraction = golden["features"][pp.raw_fraction_column(LEADS[0])]
    return {
        **golden,
        "month": pp.year_months_from_epoch(golden["t"]),
        "day": golden["t"] // 86_400,
        "baseline": {
            lead: np.asarray(
                fit_isotonic(fraction, golden["truth"][lead][0]).predict(fraction),
                dtype=np.float64,
            )
            for lead in LEADS
        },
    }


def test_the_baseline_can_itself_be_a_refitted_model(synthetic: dict) -> None:
    """``--baseline refit-v1``: both arms fitted in the same folds.

    The point is that the baseline is out of fold too. A v1 model scored
    in sample against a v2 model scored out of fold would be a comparison
    of two different protocols dressed up as a comparison of two designs.
    """
    result = pp.leave_one_month_out(
        synthetic["features"], synthetic["truth"], list(LEADS),
        month=synthetic["month"], day=synthetic["day"],
        baseline=synthetic["baseline"],
        settings=pp.FitSettings(design=pp.DESIGN_V2),
        baseline_settings=pp.FitSettings(design=pp.DESIGN_V1),
        baseline_label="refit-v1", n_resamples=0,
    )
    assert result["settings"]["baseline"] == "refit-v1"
    assert result["settings"]["baseline_fit"]["design"] == pp.DESIGN_V1
    assert result["settings"]["fit"]["design"] == pp.DESIGN_V2
    held = result["baseline_out_of_fold"]
    assert set(held) == set(LEADS)
    # A refitted baseline is a model's out-of-fold prediction, so it is
    # NOT the served curve it replaced.
    assert not np.allclose(
        held[20], np.asarray(synthetic["baseline"][20]), atol=1e-6,
    )


