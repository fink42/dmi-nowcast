def test_v2_takes_its_extra_columns_from_the_catalogue_at_run_time() -> None:
    """A column the replay grows must reach the design without an edit here.

    The feature side of this module appends to the catalogue; the model
    side is not allowed to carry a second copy of those names. So the
    check is behavioural: invent a column, and it appears.
    """
    catalogue = pp.feature_columns((20,))
    spec = pp.design_spec(None, (20,), version=pp.DESIGN_V2)
    names = {name for name, _definition in catalogue}
    # Everything the v1 design does not already read, and nothing else.
    assert set(spec.extra_columns) <= names
    assert "raw_frac_20" not in spec.extra_columns
    assert "bulk_kmh" not in spec.extra_columns


def test_an_invented_catalogue_column_reaches_the_design(monkeypatch) -> None:
    def catalogue(leads):
        return pp.feature_columns.__wrapped__(leads) if hasattr(
            pp.feature_columns, "__wrapped__",
        ) else (("brand_new_score", "invented by a test"),)

    monkeypatch.setattr(pp, "feature_columns", catalogue)
    spec = pp.design_spec(None, (20,), version=pp.DESIGN_V2)
    assert "brand_new_score" in spec.extra_columns
    names = pp.design_columns((20,), spec)
    assert "brand_new_score" in names
    row = {"brand_new_score": np.array([2.5]), **_one_row()}
    design = pp.build_design(row, (20,), spec)
    assert design[0, list(names).index("brand_new_score")] == 2.5


class TestTheLog1pDecision:
    """Which extra columns are rates, decided from the values, then stored.

    The catalogue holds rain rates whose names do not say so
    (``ens_mean_20``, ``up_max_b0``), so a name rule alone would quietly
    undo in v2 the one transform the v1 design was careful to apply.
    """

    def test_a_name_that_says_it_is_a_rate_is_enough(self) -> None:
        assert pp.wants_log1p("up_mean_40km_mm_h")
        assert pp.wants_log1p("station_radar_km")
        assert not pp.wants_log1p("g_dry_60")

    def test_a_heavy_tailed_non_negative_column_is_caught_by_its_values(self) -> None:
        rng = np.random.default_rng(2)
        rate = np.where(
            rng.uniform(size=4000) < 0.7, 0.0, np.exp(rng.normal(0.5, 1.2, 4000)),
        )
        assert pp.wants_log1p("ens_mean_20", rate)

    def test_a_fraction_a_count_and_a_signed_column_are_left_alone(self) -> None:
        rng = np.random.default_rng(3)
        assert not pp.wants_log1p("share", rng.uniform(0.0, 1.0, 4000))
        assert not pp.wants_log1p("minutes", rng.uniform(0.0, 360.0, 4000))
        assert not pp.wants_log1p("anomaly", rng.normal(size=4000))

    def test_the_decision_is_stored_and_replayed_not_re_derived(self) -> None:
        rng = np.random.default_rng(12)
        rows = _rows_with_motion(4000)
        rows["ens_mean_20"] = np.where(
            rng.uniform(size=4000) < 0.7, 0.0, np.exp(rng.normal(0.5, 1.2, 4000)),
        )
        spec = pp.design_spec(rows, (20,), version=pp.DESIGN_V2)
        assert "ens_mean_20" in spec.log_columns
        names = pp.design_columns((20,), spec)
        assert "log1p_ens_mean_20" in names
        design = pp.build_design(rows, (20,), spec)
        column = design[:, list(names).index("log1p_ens_mean_20")]
        assert column == pytest.approx(np.log1p(rows["ens_mean_20"]))
        # A different set of rows does NOT change the transform: the spec
        # carries the decision, and a serving path replays it.
        other = _rows_with_motion(400, seed=9)
        other["ens_mean_20"] = np.zeros(400)
        replayed = pp.build_design(other, (20,), spec)
        column = replayed[:, list(names).index("log1p_ens_mean_20")]
        assert column.tolist() == [0.0] * 400


