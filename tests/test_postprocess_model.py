def test_a_season_with_enough_rows_gets_its_own_curve() -> None:
    rng = np.random.default_rng(9)
    n = pp.MIN_SEASON_ISOTONIC_ROWS * 3
    season = np.array(
        ["summer", "winter", "shoulder"] * pp.MIN_SEASON_ISOTONIC_ROWS, dtype="<U8",
    )
    score = rng.uniform(size=n)
    # Summer is over-confident and winter under-confident at the same score.
    rate = np.where(season == "summer", score * 0.5, np.minimum(score * 1.4, 1.0))
    y = (rng.uniform(size=n) < rate).astype(np.float64)
    pooled, curves = pp.fit_isotonic_by_season(score, y, season)
    assert set(curves) == {"summer", "winter", "shoulder"}
    at = 0.8
    assert float(curves["summer"].predict(np.array([at]))[0]) < float(
        pooled.predict(np.array([at]))[0]
    )
    assert float(curves["winter"].predict(np.array([at]))[0]) > float(
        pooled.predict(np.array([at]))[0]
    )


def test_a_thin_season_keeps_the_pooled_curve() -> None:
    rng = np.random.default_rng(10)
    n = pp.MIN_SEASON_ISOTONIC_ROWS + 100
    season = np.array(["summer"] * (n - 100) + ["winter"] * 100, dtype="<U8")
    score = rng.uniform(size=n)
    y = (rng.uniform(size=n) < score).astype(np.float64)
    _pooled, curves = pp.fit_isotonic_by_season(score, y, season)
    assert set(curves) == {"summer"}


def test_the_per_season_model_uses_the_row_s_own_curve() -> None:
    lead = pp.LeadModel(
        lead_min=20, intercept=0.0, coefficients=(1.0,),
        isotonic=IsotonicCalibrator((0.0, 1.0), (0.0, 1.0)),
        n=10, base_rate=0.1, converged=True, iterations=1,
        isotonic_by_season={
            "summer": IsotonicCalibrator((0.0, 1.0), (0.0, 0.2)),
        },
    )
    raw = np.array([1.0, 1.0])
    season = np.array(["summer", "winter"], dtype="<U8")
    assert lead.calibrate(raw, season).tolist() == pytest.approx([0.2, 1.0])
    # Without a season the pooled curve answers for every row.
    assert lead.calibrate(raw).tolist() == pytest.approx([1.0, 1.0])


