"""Post-processing v2: the design, the fit, and the evaluation protocol.

``tests/test_postprocess.py`` owns the FEATURES — the corridor geometry,
the catalogue, the transform of each stored column. This file owns
everything downstream of them: which columns the design is made of, how
the model is fitted, and how a candidate is scored against a baseline.

The first two tests are the ones that matter most. The v1 design and the
v1 fit are what is in service, and every addition here is supposed to be
*additive*: a run that asks for nothing new must produce the same design
matrix and the same coefficients it produced before any of this existed.
They are pinned against ``fixtures/postprocess_v1_golden.json``, which
was generated by running the pre-v2 module over the same fixtures — so
the comparison is with the code that shipped, not with a restatement of
it.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pytest

from dmi_nowcast_core import postprocess as pp
from dmi_nowcast_core.calibrate import IsotonicCalibrator
from tests.golden_fixture import (
    GOLDEN_DESIGN_LEADS,
    GOLDEN_LEADS,
    golden_dataset,
    golden_row,
)

#: The leads the golden pin and the evaluation tests use.
LEADS = GOLDEN_LEADS

#: The v1 design and the v1 fit, as the PRE-v2 module produced them on
#: ``tests/golden_fixture.py``'s rows. Regenerating it is a deliberate
#: act: it means the model in service has been changed on purpose.
GOLDEN = json.loads(
    (Path(__file__).parent / "fixtures" / "postprocess_v1_golden.json").read_text()
)


def _one_row() -> dict:
    return golden_row()


def _golden_features() -> dict:
    """The golden dataset's rows with ``season`` / ``hour_utc`` derived."""
    data = golden_dataset()
    features = dict(data["features"])
    features["season"] = pp.seasons_from_epoch(data["t"])
    features["hour_utc"] = pp.hours_from_epoch(data["t"]).astype(np.float64)
    # ``features`` LAST: ``data`` carries a key of that name too, and the
    # one this returns has to be the augmented copy.
    return {**data, "features": features}


