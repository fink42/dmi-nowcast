#!/usr/bin/env node
/**
 * make-denmark-outline.mjs — the coarse Denmark outline the quality page's
 * station scatter is drawn on.
 *
 * Source: `data/denmark_boundary.geojson` in this repository — the ADMIN =
 * 'Denmark' feature of Natural Earth 1:10m Admin 0 (public domain, credited
 * on the /data page). The full feature is ~47 kB of coordinates for 15
 * polygons; a background shape at ~360 px wide needs nothing like that, so
 * this keeps the largest landmasses, simplifies each with Douglas–Peucker at
 * a tolerance of about a kilometre, and rounds to three decimals (~100 m).
 *
 * Output: `src/lib/quality/denmark.ts`, rings of [lon, lat] in degrees. The
 * projection lives in TypeScript (see `project()` there) so the outline and
 * the stations plotted on top of it cannot drift apart.
 *
 *   node scripts/make-denmark-outline.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../data/denmark_boundary.geojson');
const TARGET = resolve(here, '../src/lib/quality/denmark.ts');

/** Douglas–Peucker tolerance in degrees of longitude at 56° N (~1 km). */
const TOLERANCE = 0.016;
/** How many landmasses to keep, largest first (Bornholm is ~10th). */
const KEEP = 11;

const sqSegDistance = ([px, py], [ax, ay], [bx, by]) => {
	let x = ax;
	let y = ay;
	let dx = bx - ax;
	let dy = by - ay;
	if (dx !== 0 || dy !== 0) {
		const t = ((px - x) * dx + (py - y) * dy) / (dx * dx + dy * dy);
		if (t > 1) {
			x = bx;
			y = by;
		} else if (t > 0) {
			x += dx * t;
			y += dy * t;
		}
	}
	dx = px - x;
	dy = py - y;
	return dx * dx + dy * dy;
};

/** Douglas–Peucker, iterative, on a ring of [lon, lat]. */
function simplify(points, tolerance) {
	if (points.length <= 4) return points;
	const sqTolerance = tolerance * tolerance;
	const keep = new Uint8Array(points.length);
	keep[0] = 1;
	keep[points.length - 1] = 1;
	const stack = [[0, points.length - 1]];
	while (stack.length) {
		const [first, last] = stack.pop();
		let index = -1;
		let maxSq = sqTolerance;
		for (let i = first + 1; i < last; i++) {
			const sq = sqSegDistance(points[i], points[first], points[last]);
			if (sq > maxSq) {
				index = i;
				maxSq = sq;
			}
		}
		if (index === -1) continue;
		keep[index] = 1;
		stack.push([first, index], [index, last]);
	}
	return points.filter((_, i) => keep[i] === 1);
}

/** Shoelace area in square degrees, latitude-corrected — only used for ranking. */
function area(ring) {
	let sum = 0;
	for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
		const [xi, yi] = ring[i];
		const [xj, yj] = ring[j];
		sum += (xj - xi) * (yi + yj);
	}
	return Math.abs(sum / 2) * Math.cos((56 * Math.PI) / 180);
}

const geojson = JSON.parse(readFileSync(SOURCE, 'utf8'));
const feature = geojson.features[0];
const polygons =
	feature.geometry.type === 'MultiPolygon'
		? feature.geometry.coordinates
		: [feature.geometry.coordinates];

// Outer rings only: a hole inside Denmark at this scale is a lake, and the
// scatter's background is not a hydrological map.
const rings = polygons
	.map((polygon) => polygon[0])
	.sort((a, b) => area(b) - area(a))
	.slice(0, KEEP)
	.map((ring) => simplify(ring, TOLERANCE).map(([lon, lat]) => [+lon.toFixed(3), +lat.toFixed(3)]));

const total = rings.reduce((n, ring) => n + ring.length, 0);
const lons = rings.flat().map(([lon]) => lon);
const lats = rings.flat().map(([, lat]) => lat);

const body = rings
	.map((ring) => `\t[\n\t\t${ring.map(([lon, lat]) => `[${lon}, ${lat}]`).join(',\n\t\t')}\n\t]`)
	.join(',\n');

const source = `/**
 * A coarse outline of Denmark, as rings of [lon, lat] in degrees.
 *
 * Generated by \`scripts/make-denmark-outline.mjs\` from
 * \`data/denmark_boundary.geojson\` (Natural Earth 1:10m Admin 0, ADMIN =
 * 'Denmark', public domain — credited on the /data page): the ${KEEP} largest
 * landmasses, Douglas–Peucker simplified at ${TOLERANCE}° (~1 km) and rounded to
 * three decimals. ${total} points in total. Do not hand-edit — regenerate.
 *
 * It is background for the station scatter on the quality page and nothing
 * else: coastlines at this tolerance are decoration, not geography.
 */
export const DENMARK_OUTLINE: readonly (readonly (readonly [number, number])[])[] = [
${body}
];
`;

writeFileSync(TARGET, source);
console.log(
	`wrote ${TARGET}: ${rings.length} rings, ${total} points, ` +
		`lon ${Math.min(...lons)}…${Math.max(...lons)}, lat ${Math.min(...lats)}…${Math.max(...lats)}`
);
